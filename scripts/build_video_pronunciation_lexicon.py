"""Build pinned local phoneme assets; no network, inference, or paid calls."""

import argparse
import base64
import gzip
import hashlib
import io
import json
from pathlib import Path
import re

from scripts.offline_video_pronunciation import (
    CMUDICT_LICENSE_SHA256, CMUDICT_REVISION, CMUDICT_SHA256, load_cmudict,
)

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/video_pronunciation"
SCHEMA = "cmudict-unique-stressed-phones-v1"
MATCHING_CONFIG = {
    "rule": "exact-or-reviewed-v3-or-unique-complete-stressed-phones-v1",
    "normalization": "nfkc-curly-apostrophe-casefold-whole-hey-tail-v1",
    "max_tail_tokens": 4,
    "max_token_chars": 32,
    "max_sequence_phones": 64,
    "max_transcript_chars": 512,
    "ambiguous_oov_or_different": "pronunciation_unresolved",
    "preserve_reviewed_v3_groups": True,
    "infer_or_drop_phones": False,
}


def sha(content):
    return hashlib.sha256(content).hexdigest()


def build(source, license_path):
    lexicon = load_cmudict(source)
    license_bytes = Path(license_path).read_bytes()
    if sha(license_bytes) != CMUDICT_LICENSE_SHA256:
        raise ValueError("license_hash_mismatch")
    words = {}
    for word, variants in lexicon.pronunciations.items():
        distinct = set(variants)
        if (len(word) <= 32 and re.fullmatch(r"[a-z]+(?:[-'][a-z]+){0,2}", word)
                and len(distinct) == 1):
            words[word] = " ".join(next(iter(distinct)))
    raw = (json.dumps(words, sort_keys=True, ensure_ascii=True, separators=(",", ":")) + "\n").encode()
    target = io.BytesIO()
    with gzip.GzipFile(filename="", fileobj=target, mode="wb", compresslevel=9, mtime=0) as stream:
        stream.write(raw)
    compressed = target.getvalue()
    manifest = {
        "schema": SCHEMA,
        "source_revision": CMUDICT_REVISION,
        "source_sha256": CMUDICT_SHA256,
        "license_sha256": CMUDICT_LICENSE_SHA256,
        "json_sha256": sha(raw),
        "gzip_sha256": sha(compressed),
        "json_bytes": len(raw),
        "gzip_bytes": len(compressed),
        "entries": len(words),
        "eligible_words": "ascii-letters-up-to-two-hyphens-or-apostrophes-max32",
        "ambiguity_rule": "one-distinct-full-sequence-including-stress",
    }
    constants = ("# Generated by scripts/build_video_pronunciation_lexicon.py.\n"
                 "# These data identities are separate from all existing speech policies.\n"
                 "LEXICON_MANIFEST = " + repr(manifest) + "\n"
                 "MATCHING_CONFIG = " + repr(MATCHING_CONFIG) + "\n").encode()
    # The literal is inside a function: old policies never inflate or parse it.
    license_notice = "".join("// " + line + "\n" for line in license_bytes.decode("utf-8").splitlines())
    javascript = license_notice + '''// Generated pinned data; regenerate with build_video_pronunciation_lexicon.py.
var VIDEO_PRONUNCIATION_LEXICON_V24_CACHE_ = null;
function videoPronunciationLexiconManifestV24_() { return MANIFEST; }
function videoPronunciationLexiconV24_() {
  if (VIDEO_PRONUNCIATION_LEXICON_V24_CACHE_) return VIDEO_PRONUNCIATION_LEXICON_V24_CACHE_;
  var manifest = videoPronunciationLexiconManifestV24_();
  function digest(bytes) {
    return Utilities.computeDigest(Utilities.DigestAlgorithm.SHA_256, bytes).map(function(value) {
      return ("0" + ((value + 256) % 256).toString(16)).slice(-2);
    }).join("");
  }
  var compressed = Utilities.base64Decode("PAYLOAD");
  if (compressed.length !== manifest.gzip_bytes || digest(compressed) !== manifest.gzip_sha256)
    throw new Error("pronunciation_lexicon_integrity");
  var blob = Utilities.ungzip(Utilities.newBlob(compressed, "application/gzip"));
  var raw = blob.getBytes();
  if (raw.length !== manifest.json_bytes || digest(raw) !== manifest.json_sha256)
    throw new Error("pronunciation_lexicon_integrity");
  var parsed = JSON.parse(blob.getDataAsString("UTF-8"));
  var keys = Object.keys(parsed);
  if (keys.length !== manifest.entries) throw new Error("pronunciation_lexicon_integrity");
  var lookup = Object.create(null);
  keys.forEach(function(key) { lookup[key] = parsed[key]; });
  VIDEO_PRONUNCIATION_LEXICON_V24_CACHE_ = Object.freeze(lookup);
  return VIDEO_PRONUNCIATION_LEXICON_V24_CACHE_;
}
'''.replace("MANIFEST", json.dumps(manifest, sort_keys=True, separators=(",", ":"))).replace(
        "PAYLOAD", base64.b64encode(compressed).decode())
    return {
        DATA / "unique-phones-v1.json.gz": compressed,
        DATA / "manifest.json": (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode(),
        DATA / "LICENSE-CMUdict": license_bytes,
        ROOT / "video_followup_pronunciation_data.py": constants,
        ROOT / "apps_script/video_pronunciation_lexicon.js": javascript.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--license", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    artifacts = build(args.source, args.license)
    for path, content in artifacts.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise SystemExit("Generated pronunciation asset differs: " + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(json.dumps({"checked": args.check, "artifacts": {
        str(path.relative_to(ROOT)): {"bytes": len(content), "sha256": sha(content)}
        for path, content in artifacts.items()}}, sort_keys=True))


if __name__ == "__main__":
    main()
